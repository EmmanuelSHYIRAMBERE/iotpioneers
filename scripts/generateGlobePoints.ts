/**
 * Generates lib/globePoints.ts, the land dots for the hero globe (connected-globe-hero skill).
 *
 * Source: Natural Earth 1:110m Physical Vectors, "Land" (ne_110m_land.geojson), public domain.
 * https://www.naturalearthdata.com/  (GeoJSON mirror:
 * https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson)
 *
 * Run once: npx tsx scripts/generateGlobePoints.ts <path to ne_110m_land.geojson>
 *
 * The sphere is sampled on an approximately equal-area grid: rows every STEP degrees of latitude,
 * and within each row a longitude step of STEP / cos(latitude). Land cells are stored as runs of
 * column indices per row, which keeps the module a few kilobytes. `decodeGlobePoints` in
 * components/visuals/globeEngine.ts rebuilds the latitude and longitude of every dot.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const STEP = 1.9;
/** Antarctica is left out: at this tilt it only adds a dense white cap at the bottom edge. */
const MIN_LAT = -58;

type Ring = readonly (readonly [number, number])[];
type Polygon = readonly Ring[];

interface Geometry {
  type: "Polygon" | "MultiPolygon";
  coordinates: unknown;
}

function polygonsOf(geometry: Geometry): Polygon[] {
  if (geometry.type === "Polygon") return [geometry.coordinates as Polygon];
  return geometry.coordinates as Polygon[];
}

function inRing(lon: number, lat: number, ring: Ring): boolean {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i, i += 1) {
    const a = ring[i];
    const b = ring[j];
    if (!a || !b) continue;
    const [xi, yi] = a;
    const [xj, yj] = b;
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

function inPolygon(lon: number, lat: number, polygon: Polygon): boolean {
  const [outer, ...holes] = polygon;
  if (!outer || !inRing(lon, lat, outer)) return false;
  return !holes.some((hole) => inRing(lon, lat, hole));
}

function main(): void {
  const input = process.argv[2];
  if (!input) throw new Error("Usage: tsx scripts/generateGlobePoints.ts <ne_110m_land.geojson>");
  const data = JSON.parse(readFileSync(input, "utf8")) as {
    features: { geometry: Geometry }[];
  };
  const polygons = data.features.flatMap((feature) => polygonsOf(feature.geometry));

  const rows: string[] = [];
  let points = 0;
  for (let r = 0; ; r += 1) {
    const lat = 90 - STEP / 2 - r * STEP;
    if (lat < MIN_LAT) break;
    const count = Math.max(1, Math.floor(360 / (STEP / Math.cos((lat * Math.PI) / 180))));
    const runs: string[] = [];
    let runStart = -1;
    for (let i = 0; i <= count; i += 1) {
      const lon = -180 + ((i + 0.5) * 360) / count;
      const land = i < count && polygons.some((polygon) => inPolygon(lon, lat, polygon));
      if (land) {
        points += 1;
        if (runStart < 0) runStart = i;
      } else if (runStart >= 0) {
        runs.push(i - 1 === runStart ? String(runStart) : `${String(runStart)}-${String(i - 1)}`);
        runStart = -1;
      }
    }
    rows.push(runs.join(","));
  }

  const out = `/**
 * Land dots for the hero globe. GENERATED by scripts/generateGlobePoints.ts; do not edit.
 * Source: Natural Earth 1:110m land (public domain), https://www.naturalearthdata.com/
 * ${String(points)} points on a ${String(STEP)} degree equal-area grid, latitudes ${String(MIN_LAT)} to 90.
 * Each row lists runs of land column indices; decode with decodeGlobePoints (globeEngine.ts).
 * Imported dynamically only, never in the first load bundle.
 */
export const GLOBE_STEP_DEG = ${String(STEP)};
export const GLOBE_POINT_COUNT = ${String(points)};
export const GLOBE_ROWS: readonly string[] = ${JSON.stringify(rows)};
`;
  const target = join(process.cwd(), "lib", "globePoints.ts");
  writeFileSync(target, out);
  console.log(`points ${String(points)}, rows ${String(rows.length)}, bytes ${String(out.length)}`);
}

main();
